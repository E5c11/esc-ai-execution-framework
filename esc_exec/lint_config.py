"""Generate an ESLint flat configuration (TypeScript) from the architecture's lintable rules.

The framework holds the *mapping* from architecture rules to lint rules. It holds none of the numbers: every size
limit comes from the project's own declared limits (``.esc-ai/lint-limits.yaml``) and generation fails when one is
missing, so a limit is always a decision the project made (see ``platforms/web/README.md``, "Project-set values").

Only rules a linter can check are mapped. The rest stay with ``esc-exec architecture check`` (import direction,
forbidden folder names) or with a reviewer; ``COVERAGE`` records which is which, so nothing is silently dropped.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from esc_exec.yaml_io import load_yaml

LIMITS_FILE = ".esc-ai/lint-limits.yaml"
TEMPLATES = ("web-app",)

REQUIRED_LIMITS = {
    "maxModuleLines": "ARCH-WEB-APP-MOD-SIZE-01",
    "maxFunctionLines": "ARCH-WEB-APP-MOD-FUNC-01",
    "maxComplexity": "ARCH-WEB-APP-MOD-FUNC-01",
}
OPTIONAL_LIMITS = {
    "maxComponentFunctionLines": "a larger function-length limit for JSX components under components/",
}

# Rules, and how far a linter can check them. "full" = the lint rule is the whole rule; "partial" = it covers
# the mechanical part and the rest stays with a reviewer; "architecture-check" = covered by `architecture check`.
COVERAGE: dict[str, tuple[str, str]] = {
    "ARCH-WEB-APP-MOD-SIZE-01": ("full", "max-lines"),
    "ARCH-WEB-APP-MOD-FUNC-01": ("partial", "max-lines-per-function, complexity (the compute/IO split stays with a reviewer)"),
    "ARCH-WEB-APP-MOD-CYCLE-01": ("full", "import-x/no-cycle"),
    "ARCH-WEB-APP-MOD-API-01": ("partial", "no `export *` in index.ts (the explicit-exports and import-from-surface halves are the architecture check)"),
    "ARCH-WEB-APP-MOD-NAME-01": ("architecture-check", "forbidden-path in the web-app template (web.no-grab-bag-names)"),
    "ARCH-WEB-APP-EFLOW-ASSERT-01": ("partial", "no non-null assertion, no @ts-ignore, no object-literal assertion; a plain `x as T` over unchecked data cannot be told from a legitimate narrowing"),
    "ARCH-WEB-APP-EFLOW-SWALLOW-01": ("partial", "no empty catch, no floating promise"),
    "ARCH-WEB-APP-OBS-LOG-01": ("partial", "no console.* (the injected logger is a convention)"),
    "ARCH-WEB-APP-DOM-CLOCK-01": ("full", "no Date.now(), new Date(), Math.random(), crypto.randomUUID() in domain and useCases"),
    "ARCH-WEB-APP-DOM-TABLE-02": ("partial", "switch-exhaustiveness-check (keyword-list completeness is a test)"),
    "PLAT-WEB-RP-DEPS-01": ("full", "react-hooks/exhaustive-deps"),
    "PLAT-WEB-RP-EFFECT-01": ("partial", "react-hooks/rules-of-hooks (effects-for-derived-state is a reviewer rule)"),
    "PLAT-WEB-TS-ANY-01": ("full", "@typescript-eslint/no-explicit-any"),
}


def load_limits(root: Path, path: Path | None = None) -> dict[str, Any]:
    source = path or root / LIMITS_FILE
    if not source.is_file():
        raise ValueError(
            f"no declared limits at {source}; the framework sets no default sizes. Create it with "
            f"{', '.join(REQUIRED_LIMITS)} (and optionally {', '.join(OPTIONAL_LIMITS)})."
        )
    limits = load_yaml(source) or {}
    for name, rule in REQUIRED_LIMITS.items():
        value = limits.get(name)
        if not isinstance(value, int) or isinstance(value, bool) or value < 1:
            raise ValueError(f"{source}: {name} must be a positive integer (needed by {rule})")
    value = limits.get("maxComponentFunctionLines")
    if value is not None and (not isinstance(value, int) or isinstance(value, bool) or value < 1):
        raise ValueError(f"{source}: maxComponentFunctionLines must be a positive integer")
    return limits


def generate_eslint_config(limits: dict[str, Any], template: str = "web-app") -> str:
    if template not in TEMPLATES:
        raise ValueError(f"unknown lint template: {template} (known: {', '.join(TEMPLATES)})")
    component_limit = limits.get("maxComponentFunctionLines")
    component_block = ""
    if component_limit:
        component_block = f"""
  {{
    // Components are mostly markup, so their function-length limit is declared separately (maxComponentFunctionLines).
    files: ['src/**/components/**/*.tsx'],
    rules: {{
      'max-lines-per-function': ['error', {{ max: {component_limit}, skipBlankLines: true, skipComments: true }}],
    }},
  }},"""
    return f"""// Generated by `esc-exec architecture lint-config generate` from the architecture's lintable rules.
// Do not edit the rules here: change the rule or the limits in {LIMITS_FILE}, then regenerate.
// Needs: eslint (9+), typescript-eslint, eslint-plugin-react-hooks, eslint-plugin-import-x, jiti.
import tseslint from 'typescript-eslint';
import reactHooks from 'eslint-plugin-react-hooks';
import importX from 'eslint-plugin-import-x';

const sourceFiles = ['src/**/*.{{ts,tsx}}'];
const pure = ['src/**/domain/**/*.ts', 'src/**/useCases/**/*.ts'];

export default tseslint.config(
  {{ ignores: ['dist/**', 'node_modules/**', '**/*.test.ts', '**/*.test.tsx', '**/*.contract.ts'] }},
  {{
    files: sourceFiles,
    languageOptions: {{
      parser: tseslint.parser,
      parserOptions: {{ projectService: true, tsconfigRootDir: import.meta.dirname }},
    }},
    plugins: {{ '@typescript-eslint': tseslint.plugin, 'react-hooks': reactHooks, 'import-x': importX }},
    rules: {{
      // ARCH-WEB-APP-MOD-SIZE-01
      'max-lines': ['error', {{ max: {limits['maxModuleLines']}, skipBlankLines: true, skipComments: true }}],
      // ARCH-WEB-APP-MOD-FUNC-01
      'max-lines-per-function': ['error', {{ max: {limits['maxFunctionLines']}, skipBlankLines: true, skipComments: true }}],
      complexity: ['error', {limits['maxComplexity']}],
      // ARCH-WEB-APP-MOD-CYCLE-01
      'import-x/no-cycle': 'error',
      // ARCH-WEB-APP-EFLOW-ASSERT-01 (the mechanical part)
      '@typescript-eslint/consistent-type-assertions': ['error', {{ assertionStyle: 'as', objectLiteralTypeAssertions: 'never' }}],
      '@typescript-eslint/no-non-null-assertion': 'error',
      '@typescript-eslint/ban-ts-comment': 'error',
      // PLAT-WEB-TS-ANY-01
      '@typescript-eslint/no-explicit-any': 'error',
      // ARCH-WEB-APP-EFLOW-SWALLOW-01 (the mechanical part)
      'no-empty': ['error', {{ allowEmptyCatch: false }}],
      '@typescript-eslint/no-floating-promises': 'error',
      // ARCH-WEB-APP-DOM-TABLE-02 (exhaustive switch)
      '@typescript-eslint/switch-exhaustiveness-check': 'error',
      // ARCH-WEB-APP-OBS-LOG-01 (the mechanical part)
      'no-console': 'error',
      // PLAT-WEB-RP-DEPS-01, PLAT-WEB-RP-EFFECT-01
      'react-hooks/rules-of-hooks': 'error',
      'react-hooks/exhaustive-deps': 'error',
    }},
  }},{component_block}
  {{
    // ARCH-WEB-APP-MOD-API-01: a public surface lists its exports explicitly.
    files: ['src/**/index.ts'],
    rules: {{
      'no-restricted-syntax': ['error', {{ selector: 'ExportAllDeclaration', message: 'Do not use `export *` in a public surface; list the exports.' }}],
    }},
  }},
  {{
    // ARCH-WEB-APP-DOM-CLOCK-01: domain and use cases take the time and randomness as arguments.
    files: pure,
    rules: {{
      'no-restricted-properties': [
        'error',
        {{ object: 'Date', property: 'now', message: 'Take the time as an argument.' }},
        {{ object: 'Math', property: 'random', message: 'Take randomness as an argument.' }},
        {{ object: 'crypto', property: 'randomUUID', message: 'Take the id as an argument.' }},
      ],
      'no-restricted-syntax': ['error', {{ selector: "NewExpression[callee.name='Date'][arguments.length=0]", message: 'Take the time as an argument.' }}],
    }},
  }},
);
"""


def write_eslint_config(repository: Path, component_id: str, template: str = "web-app",
                        limits_path: Path | None = None, force: bool = False) -> Path:
    from esc_exec.indexing import INDEX_FILE
    from esc_exec.json_io import load_json
    from esc_exec.manifests import ESC_AI_DIR

    index = load_json(repository / ESC_AI_DIR / INDEX_FILE)
    component = next((item for item in index["components"] if item["id"] == component_id), None)
    if not component:
        raise ValueError(f"component is not in repository index: {component_id}")
    root = repository / component["path"]
    # limits are the repository's decision, so they live at the repository root unless a path is given
    limits = load_limits(repository, limits_path)
    output = root / "eslint.config.ts"
    if output.exists() and not force:
        raise ValueError(f"{output} already exists; pass --force to regenerate it")
    output.write_text(generate_eslint_config(limits, template), encoding="utf-8")
    return output


def lint_coverage_table() -> list[dict[str, str]]:
    return [{"rule": rule, "coverage": kind, "by": by} for rule, (kind, by) in COVERAGE.items()]
